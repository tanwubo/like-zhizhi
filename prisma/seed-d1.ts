type SqlValue = string | number | boolean | null | SqlRaw;

class SqlRaw {
  constructor(readonly value: string) {}
}

function raw(value: string) {
  return new SqlRaw(value);
}

function escapeSql(value: string) {
  return value.replaceAll("'", "''");
}

function valueSql(value: SqlValue) {
  if (value instanceof SqlRaw) {
    return value.value;
  }
  if (value === null) {
    return "NULL";
  }
  if (typeof value === "number") {
    return String(value);
  }
  if (typeof value === "boolean") {
    return value ? "1" : "0";
  }
  return `'${escapeSql(value)}'`;
}

function quoteIdentifier(identifier: string) {
  return `"${identifier.replaceAll('"', '""')}"`;
}

function upsertSql(table: string, data: Record<string, SqlValue>, conflictColumns: string[], updateColumns: string[]) {
  const columns = Object.keys(data);
  const insertColumns = columns.map(quoteIdentifier).join(", ");
  const values = columns.map((column) => valueSql(data[column])).join(", ");
  const conflict = conflictColumns.map(quoteIdentifier).join(", ");
  const updates = updateColumns.map((column) => `${quoteIdentifier(column)} = excluded.${quoteIdentifier(column)}`).join(", ");

  return [
    `INSERT INTO ${quoteIdentifier(table)} (${insertColumns})`,
    `VALUES (${values})`,
    `ON CONFLICT(${conflict}) DO UPDATE SET ${updates};`
  ].join("\n");
}

function ownerIdSubquery(ownerEmail: string) {
  return raw(`(SELECT "id" FROM "User" WHERE "email" = '${escapeSql(ownerEmail)}')`);
}

