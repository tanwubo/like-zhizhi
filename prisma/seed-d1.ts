async function main() {
  const target = process.argv.includes("--remote") ? "--remote" : "--local";
  const ownerEmail = process.env.SEED_OWNER_EMAIL ?? "owner@example.com";
  const ownerPassword = process.env.SEED_OWNER_PASSWORD ?? "ChangeMe123!";
  const ownerPasswordHash = await bcrypt.hash(ownerPassword, 12);
  const sql = generateD1SeedSql({ ownerEmail, ownerPasswordHash });
  const outputPath = resolve(".generated", "d1-seed.sql");

  mkdirSync(dirname(outputPath), { recursive: true });
  writeFileSync(outputPath, sql, "utf8");

  const wranglerArgs = ["wrangler", "d1", "execute", "like-zhizhi", target, "--file", outputPath];
  const command = process.platform === "win32" ? "cmd.exe" : "pnpm";
  const args = process.platform === "win32" ? ["/d", "/s", "/c", "pnpm", ...wranglerArgs] : wranglerArgs;
  const result = spawnSync(command, args, { stdio: "inherit" });

  if (result.error) {
    console.error(result.error);
    process.exit(1);
  }
  if (result.status !== 0) {
    process.exit(result.status ?? 1);
  }
}

const currentFile = fileURLToPath(import.meta.url);
if (process.argv[1] && resolve(process.argv[1]) === currentFile) {
  main().catch((error) => {
    console.error(error);
    process.exit(1);
  });
}
